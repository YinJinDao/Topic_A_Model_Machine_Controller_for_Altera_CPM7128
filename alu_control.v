// ============================================================
// 文件名: alu_control.v  ——  ALU 控制接口
// 所属项目: TEC-8 模型机控制器（题目A）
// 设计者: 角色A
// 功能描述:
//   本模块根据当前执行的指令，产生 ALU（算术逻辑单元）需要的
//   控制信号。具体包括：
//     - cin  : ALU 的进位输入（加法时=0，减法/自增时=1）
//     - ldz  : 是否更新 Z 标志（结果是否为 0）
//     - ldc  : 是否更新 C 标志（是否有进位/借位）
//
// 为什么需要这个模块:
//   ALU 在做不同运算时需要不同的控制。比如：
//   - ADD 需要 cin=0（无进位），且运算后更新 Z 和 C 标志
//   - SUB 需要 cin=1（借位），且更新 Z 和 C 标志
//   - AND 需要更新 Z 标志，但不更新 C 标志（逻辑运算无进位）
//   - INC 需要 cin=1，更新 Z 和 C
//
// 信号说明:
//   is_xxx  - 输入，来自 instruction_decoder，表示当前指令
//   t1/t2   - 输入，来自 timing_gen，用于在正确节拍发出控制
//   cin     - 输出，发送给 ALU 的进位输入
//   ldz     - 输出，Z 标志寄存器的加载使能（1=允许更新）
//   ldc     - 输出，C 标志寄存器的加载使能（1=允许更新）
// ============================================================

module alu_control (
    // --- 输入端口 ---
    // 指令标识：来自 instruction_decoder 译码器
    input  wire is_add,     // 当前是 ADD 指令？
    input  wire is_sub,     // 当前是 SUB 指令？
    input  wire is_and,     // 当前是 AND 指令？
    input  wire is_inc,     // 当前是 INC 指令？
    input  wire is_ld,      // 当前是 LD 指令？

    // 时序节拍：来自 timing_gen 时序发生器
    input  wire t1,         // 时序节拍 T1
    input  wire t2,         // 时序节拍 T2
    input  wire t3,         // 时序节拍 T3

    // --- 输出端口 ---
    output reg  cin,        // ALU 进位输入（0=加法/与，1=减法/自增）
    output reg  ldz,        // Z 标志加载使能（1=运算结果影响 Z 标志）
    output reg  ldc         // C 标志加载使能（1=运算结果影响 C 标志）
);

    // ============================================================
    // 组合逻辑：根据指令类型和节拍产生 ALU 控制信号
    //
    // 设计思路：
    //   运算结果只在 T1 节拍写入目标寄存器，所以 ldz/ldc 也只在
    //   T1 节拍有效。其他节拍不需要更新标志位。
    //
    //   CIN 的取值：
    //     ADD:  cin=0（加法不需要进位输入）
    //     SUB:  cin=1（减法实质是"加补码"，需要 cin=1）
    //     AND:  cin=0（逻辑运算不需要进位）
    //     INC:  cin=1（自增 1 相当于加 1，需要 cin=1）
    //
    //   LDC 的取值：
    //     ADD/SUB/INC:  ldc=1（这些运算会产生进位/借位，需要更新 C）
    //     AND:  ldc=0（逻辑运算不影响进位标志）
    // ============================================================

    always @(*) begin
        // ---- 默认值：所有控制信号归零 ----
        // 这样写确保不会意外生成锁存器
        cin = 1'b0;
        ldz = 1'b0;
        ldc = 1'b0;

        // ---- 只在 T1 节拍产生控制信号 ----
        // TEC-8 中运算类指令在 T1 节拍完成 ALU 操作
        if (t1) begin
            // 判断指令类型并产生相应控制信号
            if (is_add) begin
                // ADD 指令：加法运算
                cin = 1'b0;         // 加法：进位输入为 0
                ldz = 1'b1;         // 更新 Z 标志
                ldc = 1'b1;         // 更新 C 标志
            end else if (is_sub) begin
                // SUB 指令：减法运算（实际是加补码）
                cin = 1'b1;         // 减法：进位输入为 1（借位）
                ldz = 1'b1;         // 更新 Z 标志
                ldc = 1'b1;         // 更新 C 标志
            end else if (is_and) begin
                // AND 指令：逻辑与运算
                cin = 1'b0;         // 逻辑运算：无进位
                ldz = 1'b1;         // 更新 Z 标志
                ldc = 1'b0;         // 不更新 C 标志（逻辑运算不影响进位）
            end else if (is_inc) begin
                // INC 指令：自增 1
                cin = 1'b1;         // 自增：需要进位输入 1（实现 +1）
                ldz = 1'b1;         // 更新 Z 标志
                ldc = 1'b1;         // 更新 C 标志
            end
            // LD 指令不在此处处理——加载指令由 control_unit 控制
        end

        // T2/T3 节拍：所有控制信号保持默认值 0
        // 因为运算结果已经在 T1 写入，T2/T3 不需要重复操作
    end

    // ============================================================
    // 控制信号总结表：
    //
    // 指令  |  节拍  |  cin  |  ldz  |  ldc  |  说明
    // ------|--------|-------|-------|-------|-----------
    // ADD   |  T1    |   0   |   1   |   1   | 加法，更新 Z/C
    // SUB   |  T1    |   1   |   1   |   1   | 减法（补码），更新 Z/C
    // AND   |  T1    |   0   |   1   |   0   | 逻辑与，只更新 Z
    // INC   |  T1    |   1   |   1   |   1   | 自增，更新 Z/C
    // LD    |  T1    |   0   |   0   |   0   | 加载不由 ALU 处理
    // 其他  |  —     |   0   |   0   |   0   | 默认值
    // ============================================================

endmodule
