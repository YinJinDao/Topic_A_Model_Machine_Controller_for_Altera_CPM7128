// ============================================================
// 文件名: tb_timing_gen.v  ——  时序发生器测试文件（Testbench）
// 所属项目: TEC-8 模型机控制器（题目A）
// 设计者: 角色A
// 功能描述:
//   这是时序发生器的"测试台"。它模拟外部环境给 timing_gen
//   模块提供时钟和复位信号，然后观察输出波形是否正确。
//
//   好比你要测试一个灯泡——你给它通电（提供输入），然后看它
//   亮不亮（检查输出）。Testbench 就是做这个的自动化测试台。
//
// 为什么需要 Testbench:
//   1. 在烧录到 CPLD 芯片之前先验证功能
//   2. 不用反复烧录芯片，省时间
//   3. 可以"慢放"波形，仔细检查时序
//
// 时序规格:
//   MF 时钟周期 = 1μs（1000ns）
//   T1/T2/T3 脉宽 = 1μs
//   微指令周期 = 3μs
// ============================================================

// `timescale 设置仿真时间单位和精度
// 1ns / 100ps 表示：时间单位是 1ns，精度到 100ps（0.1ns）
`timescale 1ns / 100ps

// ---- 测试模块 ----
// Testbench 模块没有输入输出端口——它是独立的，提供激励给被测模块
module tb_timing_gen;

    // ---- 测试信号声明 ----
    // 这里声明连接到被测模块的"虚拟"信号
    reg  clk;           // 时钟信号（reg 类型，因为我们要在代码中驱动它）
    reg  reset_n;       // 复位信号（reg 类型，由测试代码控制）
    wire t1, t2, t3;   // T 节拍输出（wire 类型，由被测模块驱动）
    wire w1, w2, w3;   // W 节拍输出（wire 类型，由被测模块驱动）

    // ---- 实例化被测模块 ----
    // 把 timing_gen 模块"放"到测试台上，给它提供信号
    timing_gen uut (    // uut = Unit Under Test（被测单元）
        .clk    (clk),     // 把测试台的 clk 连接到 timing_gen 的 clk 端口
        .reset_n(reset_n), // 同理
        .t1     (t1),
        .t2     (t2),
        .t3     (t3),
        .w1     (w1),
        .w2     (w2),
        .w3     (w3)
    );

    // ---- 时钟信号生成 ----
    // 每 500ns 翻转一次 clk，产生周期 1000ns（1μs）的方波
    // 500ns 高电平 + 500ns 低电平 = 1μs 周期，50% 占空比
    initial begin
        clk = 0;        // 初始值为 0
        forever #500 clk = ~clk;  // 每 500ns 翻转一次
    end
    // 效果：clk 在 0ns=0, 500ns=1, 1000ns=0, 1500ns=1 ...

    // ---- 测试流程 ----
    // initial 块只执行一次，从仿真开始按顺序执行
    initial begin
        // --- 打印表头 ---
        // $display 是 Verilog 的打印函数，和 C 语言的 printf 类似
        $display("=== Timing Generator Testbench ===");
        $display("测试内容：复位功能 + 时序波形检查");
        $display("");
        // $monitor 每次信号变化时自动打印一行
        // %0t = 时间, %b = 二进制
        $display("Time\t\trst\tclk\tt1\tt2\tt3\tw1\tw2\tw3");
        $monitor("%0t\t%b\t%b\t%b\t%b\t%b\t%b\t%b\t%b",
                 $time, reset_n, clk, t1, t2, t3, w1, w2, w3);

        // ============================================================
        // 测试 1：复位功能测试
        // 目的：确认复位时所有输出都为 0
        // ============================================================
        // 初始状态：clk=0, reset_n=0（复位状态）
        clk = 0;
        reset_n = 0;

        // 等待 1500ns（1.5 个时钟周期），让复位信号充分作用
        #1500;

        // 检查复位后的输出是否全部为 0
        if (t1 !== 0 || t2 !== 0 || t3 !== 0 || 
            w1 !== 0 || w2 !== 0 || w3 !== 0) begin
            $display("【失败】复位后输出应该全为 0");
            $display("  当前值: t1=%b t2=%b t3=%b w1=%b w2=%b w3=%b",
                     t1, t2, t3, w1, w2, w3);
            $finish;  // 终止仿真
        end else begin
            $display("【通过】复位功能正常，所有输出为 0");
        end

        // ============================================================
        // 测试 2：正常工作时序测试
        // 目的：检查 T1→T2→T3 是否按顺序循环
        // ============================================================
        // 释放复位
        reset_n = 1;
        $display("");
        $display("释放复位，开始检查时序波形...");

        // 等待 6 个完整的微指令周期（18μs = 18000ns）
        // 足够观察多组 T1→T2→T3 循环
        #18000;

        // ============================================================
        // 测试 3：超时检查
        // 目的：防止复位永远不起作用
        // ============================================================
        // 这个 initial 块和上面的 initial 块同时执行
        // 如果在 3000ns 后仍然没有任何 T 信号输出，判定为失败
        // 为啥用 3000ns？因为释放复位后最多等 3μs（一个完整周期）
        // 就应该看到 T1 信号了
        // 
        // fork 表示这些语句和主流程并行执行
        fork
            begin
                #3000;  // 等待 3μs
                if (t1 === 0 && t2 === 0 && t3 === 0) begin
                    $display("【失败】复位释放后没有产生时序信号");
                    $display("  可能原因：电路未启动");
                    $finish;
                end
            end
        join

        // ============================================================
        // 测试完成
        // ============================================================
        #1000;
        $display("");
        $display("=== 仿真完成 ===");
        $display("请打开波形窗口，对照以下标准检查：");
        $display("  1. T1/T2/T3 依次为高电平，不重叠");
        $display("  2. 每个 T 信号持续 1 个 MF 周期（1μs）");
        $display("  3. 完整循环周期 = 3μs");
        $display("  4. W 信号比对应 T 信号偏移半个周期");
        $display("  5. T1→T2→T3→T1→... 无限循环");
        $finish;  // 结束仿真
    end

endmodule
