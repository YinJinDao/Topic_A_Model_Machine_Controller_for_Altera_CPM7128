// ============================================================
// 文件名: instruction_decoder.v  ——  指令译码器
// 所属项目: TEC-8 模型机控制器（题目A）
// 设计者: 角色A
// 功能描述:
//   本模块负责把指令寄存器中的操作码（IR7-IR4）翻译成具体的
//   指令标识信号。比如输入是 0001，输出 is_add 变成 1，告诉
//   其他模块"当前正在执行 ADD 指令"。
//
// 为什么需要这个模块:
//   控制单元（角色B的工作）需要知道当前执行的是哪条指令，
//   才能产生对应的控制信号。但控制单元不想直接处理 4 位二进制
//   编码——那太难读了。译码器把编码翻译成有意义的信号名称，
//   让代码更清晰易读。
//
// TEC-8 指令集（共 10 条）:
//   0001 - ADD  Rj, Ri   加法运算
//   0010 - SUB  Rj, Ri   减法运算
//   0011 - AND  Rj, Ri   逻辑与运算
//   0100 - INC  Ri       自增 1
//   0101 - LD   Ri, [addr]   从内存加载到寄存器
//   0110 - ST   Ri, [addr]   从寄存器存入内存
//   0111 - JC   addr      有进位时跳转
//   1000 - JZ   addr      为零时跳转
//   1001 - JMP  addr      无条件跳转
//   1110 - STP            停机
//
// 信号说明:
//   ir[3:0]  - 输入，指令操作码（IR7-IR4）
//   is_xxx   - 输出，每个信号对应一条特定指令
//              同一时刻只有一条指令信号为 1，其余全为 0
// ============================================================

module instruction_decoder (
    // --- 输入端口 ---
    input  wire [3:0] ir,       // IR7-IR4：4 位指令操作码

    // --- 输出端口 ---
    // 每条指令对应一个输出信号，高电平表示"当前正在执行该指令"
    output reg        is_add,   // ADD  (0001) - 加法
    output reg        is_sub,   // SUB  (0010) - 减法
    output reg        is_and,   // AND  (0011) - 逻辑与
    output reg        is_inc,   // INC  (0100) - 自增 1
    output reg        is_ld,    // LD   (0101) - 从内存加载
    output reg        is_st,    // ST   (0110) - 存入内存
    output reg        is_jc,    // JC   (0111) - 进位跳转
    output reg        is_jz,    // JZ   (1000) - 零标志跳转
    output reg        is_jmp,   // JMP  (1001) - 无条件跳转
    output reg        is_stp    // STP  (1110) - 停机
);

    // ============================================================
    // 译码逻辑（组合逻辑）
    // always @(*) 表示组合逻辑——当输入 ir 变化时，输出立即变化
    // 不需要时钟信号，不存在"等待"的概念
    //
    // 为什么叫"组合逻辑"？
    //   组合逻辑的输出只取决于当前输入，像加法器一样——输入变了，
    //   输出马上跟着变。和时序逻辑（需要时钟）不同。
    // ============================================================
    always @(*) begin
        // ---- 第一步：所有输出先置 0 ----
        // 这是非常重要的写法！组合逻辑中如果没有给所有信号赋值，
        // 综合工具会生成锁存器（latch），导致电路行为异常。
        // 所以这里先把所有输出清零，下面再根据指令把对应的置 1。
        is_add = 1'b0;
        is_sub = 1'b0;
        is_and = 1'b0;
        is_inc = 1'b0;
        is_ld  = 1'b0;
        is_st  = 1'b0;
        is_jc  = 1'b0;
        is_jz  = 1'b0;
        is_jmp = 1'b0;
        is_stp = 1'b0;

        // ---- 第二步：根据操作码确定当前指令 ----
        // case 语句根据 ir 的值，执行对应分支
        // 注意这里是组合逻辑，所以用 =（阻塞赋值），不是 <=
        case (ir)
            4'b0001: is_add = 1'b1;   // ir=0001 → 是 ADD 指令
            4'b0010: is_sub = 1'b1;   // ir=0010 → 是 SUB 指令
            4'b0011: is_and = 1'b1;   // ir=0011 → 是 AND 指令
            4'b0100: is_inc = 1'b1;   // ir=0100 → 是 INC 指令
            4'b0101: is_ld  = 1'b1;   // ir=0101 → 是 LD 指令
            4'b0110: is_st  = 1'b1;   // ir=0110 → 是 ST 指令
            4'b0111: is_jc  = 1'b1;   // ir=0111 → 是 JC 指令
            4'b1000: is_jz  = 1'b1;   // ir=1000 → 是 JZ 指令
            4'b1001: is_jmp = 1'b1;   // ir=1001 → 是 JMP 指令
            4'b1110: is_stp = 1'b1;   // ir=1110 → 是 STP 指令
            default: ;                 // 其他编码：所有输出保持为 0
        endcase
    end

    // ============================================================
    // 如何测试这个模块（验证指南）：
    // 1. 创建 Testbench，依次给 ir 输入 0001~1110
    // 2. 检查对应的输出是否为 1，其他输出是否为 0
    // 3. 特别测试不存在的指令码（如 1100），确认所有输出为 0
    //
    // 测试用例示例：
    //   输入 ir=0001 → 期待 is_add=1, 其他=0
    //   输入 ir=0111 → 期待 is_jc=1,  其他=0
    //   输入 ir=1110 → 期待 is_stp=1, 其他=0
    //   输入 ir=0000 → 期待 全部=0（不存在的指令）
    // ============================================================

endmodule
