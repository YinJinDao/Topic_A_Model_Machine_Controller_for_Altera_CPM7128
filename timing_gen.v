// ============================================================
// 文件名: timing_gen.v  ——  时序发生器
// 所属项目: TEC-8 模型机控制器（题目A）
// 设计者: 角色A
// 功能描述:
//   本模块是整个控制器的"心脏"，它从外部的 MF 主时钟产生 6 个
//   时序相位信号（T1/T2/T3 + W1/W2/W3），所有其他模块都依赖
//   这些信号来同步自己的操作。
//
// 为什么需要这个模块:
//   每一条指令的执行都需要分步骤完成（取指令→译码→执行...），
//   时序发生器就是用来产生这些"步骤"的节拍信号。就像音乐的
//   节拍器一样，告诉每个模块"现在该做什么"。
//
// TEC-8 时序规格:
//   MF 时钟周期 = 1μs（微秒），占空比 50%（一半高一半低）
//   T1/T2/T3 每个脉宽 = 1μs
//   一个微指令周期 = T1 + T2 + T3 = 3μs
//   W1/W2/W3 是写选通信号，比 T 信号偏移半个时钟周期
//
// 信号说明:
//   clk      - 输入，MF 主时钟（1μs 周期方波）
//   reset_n  - 输入，复位信号（低电平有效，即 0 时复位）
//   t1,t2,t3 - 输出，三个时序节拍脉冲
//   w1,w2,w3 - 输出，三个写选通脉冲（用于控制寄存器写入时机）
// ============================================================

module timing_gen (
    // --- 输入端口 ---
    input  wire clk,        // MF 主时钟：来自外部晶振，1μs 周期
    input  wire reset_n,    // 复位信号：低电平有效，按下复位键时=0

    // --- 输出端口 ---
    output reg  t1,         // 时序相位 1：第一个节拍，高电平持续 1μs
    output reg  t2,         // 时序相位 2：第二个节拍，高电平持续 1μs
    output reg  t3,         // 时序相位 3：第三个节拍，高电平持续 1μs
    output reg  w1,         // 写选通 1：在 T1 的后半段产生，用于写操作
    output reg  w2,         // 写选通 2：在 T2 的后半段产生
    output reg  w3          // 写选通 3：在 T3 的后半段产生
);

    // ============================================================
    // 内部计数器
    // 用 2 位二进制数实现模 3 计数器（计数值：0→1→2→0→1→2→...）
    // 为什么是模 3？因为我们要产生 3 个节拍（T1/T2/T3），每个节拍
    // 占用一个 MF 时钟周期。
    //
    // 计数值 0 → 当前是 T1 阶段
    // 计数值 1 → 当前是 T2 阶段
    // 计数值 2 → 当前是 T3 阶段
    // ============================================================
    reg [1:0] count;  // [1:0] 表示 2 位宽的寄存器，可存 0~3

    // ============================================================
    // 主时序逻辑（在时钟上升沿触发）
    // 这段 always 块在每个 MF 时钟的上升沿（从 0 跳变到 1 的时刻）
    // 执行一次。它负责两件事：
    //   1. 计数器加 1（模 3 循环）
    //   2. 根据计数值产生 T1/T2/T3 信号
    //
    // 敏感信号列表 (posedge clk or negedge reset_n) 表示：
    //   - clk 上升沿时执行正常逻辑
    //   - reset_n 下降沿时（即复位）立即清零
    // ============================================================
    always @(posedge clk or negedge reset_n) begin
        if (!reset_n) begin
            // ---- 复位状态 ----
            // 当 reset_n = 0 时（复位被按下），所有信号归零
            count <= 2'b00;  // 计数器清零（2'b00 是二进制数 00）
            t1    <= 1'b0;   // 所有输出置 0
            t2    <= 1'b0;
            t3    <= 1'b0;
            w1    <= 1'b0;
            w2    <= 1'b0;
            w3    <= 1'b0;
        end else begin
            // ---- 正常工作 ----
            // 计数器加 1（模 3 循环）
            if (count == 2'b10)      // 如果当前是 2（二进制 10）
                count <= 2'b00;      // 回到 0
            else
                count <= count + 1'b1;  // 否则加 1

            // 根据当前计数值决定哪个 T 信号为高电平
            // 注意：这里使用的是非阻塞赋值(<=)，因为是时序逻辑
            case (count)
                2'b00: begin        // 计数值 0：T1 阶段
                    t1 <= 1'b1;     // T1 输出高电平
                    t2 <= 1'b0;
                    t3 <= 1'b0;
                end
                2'b01: begin        // 计数值 1：T2 阶段
                    t1 <= 1'b0;
                    t2 <= 1'b1;     // T2 输出高电平
                    t3 <= 1'b0;
                end
                2'b10: begin        // 计数值 2：T3 阶段
                    t1 <= 1'b0;
                    t2 <= 1'b0;
                    t3 <= 1'b1;     // T3 输出高电平
                end
                default: begin      // 正常情况下不会执行到这里
                    t1 <= 1'b0;     // default 分支必须写，防止生成锁存器
                    t2 <= 1'b0;
                    t3 <= 1'b0;
                end
            endcase
        end
    end

    // ============================================================
    // W 信号产生逻辑（在时钟下降沿触发）
    // W1/W2/W3 在 T1/T2/T3 的基础上偏移了半个时钟周期，这样做的
    // 目的是：让写操作发生在节拍的后半段，确保数据已经稳定。
    //
    // 敏感信号列表 (negedge clk) 表示在时钟下降沿触发，
    // 而 T 信号是在上升沿触发的，因此 W 信号自然滞后半个周期。
    // ============================================================
    always @(negedge clk or negedge reset_n) begin
        if (!reset_n) begin
            // 复位时所有 W 信号归零
            w1 <= 1'b0;
            w2 <= 1'b0;
            w3 <= 1'b0;
        end else begin
            // 根据计数器当前值产生 W 信号
            // 这里读取 count 的值——注意 count 是在上升沿更新的，
            // 而本 always 在下降沿触发，所以读到的是"上一次"的计数值
            case (count)
                2'b00: begin
                    w1 <= 1'b1;     // T1 后半段产生 W1
                    w2 <= 1'b0;
                    w3 <= 1'b0;
                end
                2'b01: begin
                    w1 <= 1'b0;
                    w2 <= 1'b1;     // T2 后半段产生 W2
                    w3 <= 1'b0;
                end
                2'b10: begin
                    w1 <= 1'b0;
                    w2 <= 1'b0;
                    w3 <= 1'b1;     // T3 后半段产生 W3
                end
                default: begin
                    w1 <= 1'b0;
                    w2 <= 1'b0;
                    w3 <= 1'b0;
                end
            endcase
        end
    end

    // ============================================================
    // 预期波形示意（方便你对照仿真结果检查）：
    //
    // 时间(ns):  0    500  1000  1500  2000  2500  3000  3500
    // clk:      ___|‾‾|___|‾‾‾|___|‾‾‾|___|‾‾‾|___|‾‾‾|___
    // count:      0      1      2      0      1      2
    // t1:       ________|‾‾‾‾|__________________|‾‾‾‾|_____
    // t2:       ________________|‾‾‾‾|__________________|‾‾‾
    // t3:       ________________________|‾‾‾‾|____________
    // w1:            |‾‾‾‾|_____________|‾‾‾‾|__________
    // w2:            ________|‾‾‾‾|_____________|‾‾‾‾|
    // w3:            ________________|‾‾‾‾|_____________
    //
    // 关键检查点：
    //   1. T1/T2/T3 依次为高电平，不重叠
    //   2. 每个 T 信号持续 1 个 MF 周期（1μs）
    //   3. 完整循环（T1→T2→T3）周期 = 3μs
    //   4. W 信号比对应 T 信号延迟半个时钟周期
    // ============================================================

endmodule
